const close = async () => {
  if (!app) return;
  const current = app; app = undefined;
  const child = current.process();
  const exited = new Promise<void>(done => child.once('exit', () => done()));
  await current.evaluate(({ app }) => app.exit(0)).catch(() => {});
  if (child.exitCode === null) await exited;
};
